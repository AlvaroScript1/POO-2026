    private void listarAlertas() {
        InstitutoMeteorologia instituto = InstitutoMeteorologia.getInstance();
        // Limpiar resultados anteriores
        modelo.setRowCount(0);
        lblResumen.setText("Cantidad de alertas: 0");
        String codigoEstacion = (String) cmbEstaciones.getSelectedItem();
        String textoInicio = txtInicio.getText().trim();
        String textoFin = txtFin.getText().trim();
        if (codigoEstacion == null || codigoEstacion.isEmpty()) { //validamos la estación
            JOptionPane.showMessageDialog(this, "Debe seleccionar una estación.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (textoInicio.isEmpty() || textoFin.isEmpty()) { //Verificar que no haya fecha vacía
            JOptionPane.showMessageDialog(this, "Debe ingresar ambas fechas.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        try { //convertir fechas al formato
            LocalDateTime inicio = LocalDateTime.parse(textoInicio, FORMATO);
            LocalDateTime fin = LocalDateTime.parse(textoFin, FORMATO);
            String[][] alertas = instituto.listaAlertas(codigoEstacion, inicio, fin);
            // AGREGAR FILAS A LA TABLA
            for (String[] fila : alertas) {
                modelo.addRow(new Object[]{fila[0], fila[1], fila[2], fila[3], fila[4] + " " + fila[5], fila[6]});
            }
            // ACTUALIZAR RESUMEN
            lblResumen.setText("Período: " + inicio.format(FORMATO) + " a " + fin.format(FORMATO) + " | Cantidad de alertas: " + alertas.length);
            if (alertas.length == 0) { //verificar que no hayan alertas
                JOptionPane.showMessageDialog(this, "La estación " + codigoEstacion + " no registra alertas en el período indicado.", "Sin resultados", JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(this, "Las fechas deben tener el formato dd/MM/yyyy HH:mm.", "Error", JOptionPane.ERROR_MESSAGE);
        } catch (MeteorologiaException e) {JOptionPane.showMessageDialog(this, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);}
    }

