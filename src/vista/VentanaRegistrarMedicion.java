    private void cargarEstaciones(){
        comboEstaciones.removeAllItems(); // se remueven todos los items al principio para despues volver a llenarse
        for(String cod : InstitutoMeteorologia.getInstance().getCodigosEstaciones()){
            comboEstaciones.addItem(cod);
        }
        cargarSensores();
    }

    private void cargarSensores(){
        comboSensores.removeAllItems();
        String codEst = (String) comboEstaciones.getSelectedItem();
        if(codEst != null){
            try{
                for(String cod : InstitutoMeteorologia.getInstance().getCodigosSensores(codEst)){
                    comboSensores.addItem(cod);
                }
            }catch(MeteorologiaException exc){
                JOptionPane.showMessageDialog(this,exc.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
        mostrarDatosSensores();
    }

    private void mostrarDatosSensores(){
        String codEst = (String) comboEstaciones.getSelectedItem();
        String codSen = (String) comboSensores.getSelectedItem();

        if(codEst == null || codSen == null){
            etiquetaTipo.setText("-");
            etiquetaUnidad.setText("");
            return;
        }
        try{
            String[] d = InstitutoMeteorologia.getInstance().getDatosSensor(codEst, codSen);
            etiquetaTipo.setText(d[0]);
            etiquetaUnidad.setText(d[1]);
        }catch(MeteorologiaException exc){
            JOptionPane.showMessageDialog(this,exc.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void registrar(){
        String codEst = (String) comboEstaciones.getSelectedItem();
        String codSen = (String) comboSensores.getSelectedItem();
        if(codEst == null || codSen == null){
            JOptionPane.showMessageDialog(this,"La estación seleccionada no tiene sensores instalados.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        String f = campoFecha.getText().trim();
        String v = campoValor.getText().trim();
        if(f.isEmpty() || v.isEmpty()){
            JOptionPane.showMessageDialog(this,"Debe completar todos los campos requeridos.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        LocalDateTime fh;
        DateTimeFormatter format = DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm");
        try{
            fh = LocalDateTime.parse(f, format);
        }catch(DateTimeParseException exc){
            JOptionPane.showMessageDialog(this, "Formato de fecha y hora inválido. Utilice dd/MM/yyyy HH:mm", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        float valor;
        try{
            valor = Float.parseFloat(v);
        }catch(NumberFormatException exc){
            JOptionPane.showMessageDialog(this, "Debe ingresar un número decimal válido.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try{
            InstitutoMeteorologia.getInstance().registraMedicion(fh, valor, codEst, codSen);
            JOptionPane.showMessageDialog(this, "Medición registrada correctamente.", "Registrar medición", JOptionPane.INFORMATION_MESSAGE);
            campoValor.setText("");
        }catch (MeteorologiaException exc){
            JOptionPane.showMessageDialog(this,exc.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }

    }


